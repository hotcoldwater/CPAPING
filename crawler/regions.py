"""지역 정규화.

한공회 게시판의 지역 값은 자유 텍스트다 — '서울', '서울 전체', '서울 강남구',
'경남 창원시 성산구', '지역무관' 이 모두 나온다. 구독 필터로 쓰려면 시·도
단위로 묶어야 한다.

**모르는 값은 무조건 '지역무관'으로 본다.** 지역 판정이 틀려서 공고를 감추면
지원자가 기회를 놓치는데, 반대로 관계없는 공고가 한 통 더 오는 것은 되돌릴 수
있다. 애매하면 보여주는 쪽이다.
"""

from __future__ import annotations

# 긴 표기를 먼저 둔다. '충청북도' 가 '충북' 보다 먼저 걸려야 한다.
_SIDO = [
    ("서울특별시", "서울"), ("서울", "서울"),
    ("경기도", "경기"), ("경기", "경기"),
    ("인천광역시", "인천"), ("인천", "인천"),
    ("부산광역시", "부산"), ("부산", "부산"),
    ("대구광역시", "대구"), ("대구", "대구"),
    ("광주광역시", "광주"), ("광주", "광주"),
    ("대전광역시", "대전"), ("대전", "대전"),
    ("울산광역시", "울산"), ("울산", "울산"),
    ("세종특별자치시", "세종"), ("세종", "세종"),
    ("강원특별자치도", "강원"), ("강원도", "강원"), ("강원", "강원"),
    ("충청북도", "충북"), ("충북", "충북"),
    ("충청남도", "충남"), ("충남", "충남"),
    ("전북특별자치도", "전북"), ("전라북도", "전북"), ("전북", "전북"),
    ("전라남도", "전남"), ("전남", "전남"),
    ("경상북도", "경북"), ("경북", "경북"),
    ("경상남도", "경남"), ("경남", "경남"),
    ("제주특별자치도", "제주"), ("제주도", "제주"), ("제주", "제주"),
]

CAPITAL = {"서울", "경기", "인천"}

# job_postings.region_group / subscribers.region_filter 가 쓰는 값
ANY = "any"          # 지역무관, 또는 판정할 수 없는 값
CAPITAL_GROUP = "capital"
LOCAL_GROUP = "local"


def sido(region: str | None) -> str | None:
    """'서울 강남구' → '서울'. 시·도를 못 찾으면 None."""
    text = (region or "").strip()
    if not text or "무관" in text:
        return None
    for prefix, name in _SIDO:
        if text.startswith(prefix):
            return name
    return None


def group(region: str | None) -> str:
    """구독 필터에 쓰는 세 값 중 하나.

    수도권(서울·경기·인천) / 지방 / 지역무관. 지역무관은 어느 필터에도
    걸리지 않고 모두에게 나간다.
    """
    name = sido(region)
    if name is None:
        return ANY
    return CAPITAL_GROUP if name in CAPITAL else LOCAL_GROUP


def label(region: str | None) -> str:
    """화면에 쓸 짧은 이름. '서울 강남구' → '서울', '지역무관' → '지역무관'."""
    return sido(region) or "지역무관"
